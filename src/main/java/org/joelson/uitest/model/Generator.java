package org.joelson.uitest.model;

public class Generator {

    private final String name;
    private int count;

    public Generator(String name, int count) {
        this.name = name;
        this.count = count;
    }

    public String getName() {
        return name;
    }

    public int getCount() {
        return count;
    }

    public void setCount(int count) {
        this.count = count;
    }
}
